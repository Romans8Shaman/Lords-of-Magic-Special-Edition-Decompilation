#!/usr/bin/env python3
"""gen_data.py: source vanilla lomse.exe .rdata and initialized .data (then BSS).

Reads ghidra_out/globals.tsv plus src/imports/iat.tsv, emits labeled assembly
at the original VAs, assembles with llvm-mingw clang (i686 ELF) + ld.lld, and
byte-compares to vanilla.

  .rdata  VA 0x0054d000  vsize 30620  rawsize 30720  (IAT, imports, RTTI, tables, strings)
  .data   VA 0x00555000  vsize 531260 rawsize 143872 (initialized slice; rest is BSS)

Outputs (under src/rdata and src/data):
  rdata.s / rdata.bin / rdata.raw / rdata.tsv
  data.s  / data.bin  / data.tsv
  bss.s   / bss.tsv     (labeled .zero tail, 387388 bytes, all zeros)

Usage: python3 tools/gen_data.py
"""
import os, sys, re, struct, hashlib, subprocess
from collections import defaultdict
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lomdb
R = lomdb.ROOT
ORIG = '/workspace/lom_project/game/LoM/English/lomse.exe'
BIN = '/opt/llvm-mingw/bin/'
GLOBALS = os.path.join(R, 'ghidra_out', 'globals.tsv')
IAT_TSV = os.path.join(R, 'src', 'imports', 'iat.tsv')
OUT_R = os.path.join(R, 'src', 'rdata')
OUT_D = os.path.join(R, 'src', 'data')
BUILD = os.path.join(R, 'build', 'data_src')

RDATA_VA, DATA_VA = 0x0054d000, 0x00555000

def pe_sections():
    import pefile
    pe = pefile.PE(ORIG)
    rs = pe.sections[1]; ds = pe.sections[2]
    assert 0x400000 + rs.VirtualAddress == RDATA_VA
    assert 0x400000 + ds.VirtualAddress == DATA_VA
    rdata = rs.get_data()[:rs.Misc_VirtualSize]
    data = ds.get_data()[:ds.SizeOfRawData]
    return pe, rdata, rs.SizeOfRawData, data, ds.Misc_VirtualSize, ds.SizeOfRawData

def lab_name(name, va):
    s = re.sub(r'[^A-Za-z0-9_]', '_', name)
    s = re.sub(r'_+', '_', s).strip('_')
    if not s or not s[0].isalpha():
        s = 'L_' + s
    if len(s) > 80:
        s = s[:60] + ('_%08x' % va)
    return s

def load_labels(rdata_end, data_end):
    """va -> (name, typ, size). Unique VA; first globals.tsv name wins, plus IAT/import labels."""
    labs = {}
    for line in open(GLOBALS):
        a = line.rstrip('\n').split('\t')
        if len(a) < 5: continue
        va = int(a[2], 16)
        if va in labs: continue
        if not (RDATA_VA <= va < rdata_end or DATA_VA <= va < data_end):
            continue
        typ, sz = a[3], a[4]
        try:
            size = int(sz)
        except ValueError:
            size = 0
        labs[va] = (lab_name(a[1], va), typ, size)
    # IAT symbols
    if os.path.exists(IAT_TSV):
        for line in open(IAT_TSV):
            if not line.strip() or line.startswith('#' ) or line.startswith('iat_va'):
                continue
            a = line.split('\t')
            va = int(a[0], 16)
            dll, sym = a[1], a[2]
            nm = lab_name('imp_%s_%s' % (dll.replace('.dll','').replace('.DLL',''), sym), va)
            labs.setdefault(va, (nm, 'iat', 4))
    return labs

def is_print(b):
    return 32 <= b < 127 or b in (9, 10, 13)

def emit_bytes(data, va0, labs, sec_name):
    """Emit AT&T-ish gas for a raw image, labels at labs keys inside the range."""
    n = len(data)
    points = sorted(set([0] + [va - va0 for va in labs if va0 <= va < va0 + n] + [n]))
    lines = [
        '# GENERATED by tools/gen_data.py — do not hand-edit',
        '.code32',
        '.section %s,"a",@progbits' % sec_name,
    ]
    used = set()
    def emit_label(off):
        va = va0 + off
        if va in labs:
            nm = labs[va][0]
            # unique in file
            if nm in used:
                nm = nm + ('_%08x' % va)
            used.add(nm)
            lines.append('%s:  # %08x %s' % (nm, va, labs[va][1]))
        lines.append('.La%08x:' % va)

    def esc_ascii(bs):
        # gas .ascii string; fall back to None if messy
        if not bs or any(b == 0 or b >= 127 or b < 32 for b in bs):
            return None
        s = bytes(bs).decode('ascii')
        if s.isprintable() and '"' not in s and '\\' not in s:
            return s
        return None

    i = 0
    while i < n:
        emit_label(i) if (va0 + i) in labs or i in points else None
        if (va0 + i) in labs or i in (0,):
            pass
        # determine this span end: next label or end
        nxt = n
        for p in points:
            if p > i:
                nxt = p; break
        # fill of identical bytes
        run = 1
        while i + run < nxt and data[i + run] == data[i]:
            run += 1
        if run >= 8:
            lines.append('  .fill %d,1,0x%02x' % (run, data[i]))
            i += run
            continue
        # C string: printable run ending at NUL before nxt (or at nxt-1)
        if is_print(data[i]) or ((va0 + i) in labs and labs[va0 + i][1] == 'string'):
            j = i
            ok = True
            while j < n and data[j] != 0:
                if not is_print(data[j]) and not ((va0 + i) in labs and labs[va0 + i][1] == 'string' and data[j] < 128):
                    # allow some 8-bit in labeled strings via .byte path
                    if data[j] < 32 or data[j] >= 127:
                        ok = False
                        break
                j += 1
            if ok and j < n and data[j] == 0 and (j - i) >= 2:
                # don't cross a later label (except we already stopped at nxt if nxt is a label)
                # if nxt < j+1, shrink
                if nxt < j + 1:
                    pass  # not a clean string to next label
                else:
                    body = data[i:j]
                    s = esc_ascii(body)
                    if s is not None:
                        lines.append('  .asciz "%s"' % s)
                    else:
                        lines.append('  .byte %s, 0x00  # string' % ', '.join('0x%02x' % b for b in body))
                    i = j + 1
                    continue
        # aligned .long runs
        if (va0 + i) % 4 == 0:
            k = i
            while k + 4 <= nxt and k + 4 <= n:
                k += 4
            if k - i >= 4:
                # emit one or more .long
                for o in range(i, k, 4):
                    v, = struct.unpack_from('<I', data, o)
                    lines.append('  .long 0x%08x' % v)
                i = k
                continue
        # leftover bytes
        chunk = data[i:nxt]
        # group into reasonable .byte lines
        for o in range(0, len(chunk), 16):
            part = chunk[o:o+16]
            lines.append('  .byte %s' % ', '.join('0x%02x' % b for b in part))
        i = nxt
    # in case the loop skipped a trailing label at n — none
    return '\n'.join(lines) + '\n'

def assemble(section, va, src_path, out_bin, want):
    os.makedirs(BUILD, exist_ok=True)
    obj = os.path.join(BUILD, section.strip('.') + '.o')
    elf = os.path.join(BUILD, section.strip('.') + '.elf')
    ld = os.path.join(BUILD, section.strip('.') + '.ld')
    open(ld, 'w').write('SECTIONS {\n  %s 0x%x : { *(%s) }\n}\n' % (section, va, section))
    r = subprocess.run([BIN + 'clang', '--target=i686-linux-gnu', '-c', src_path, '-o', obj],
                       capture_output=True, text=True)
    if r.returncode:
        print(r.stderr[-3000:])
        raise SystemExit('assemble %s failed' % section)
    r = subprocess.run([BIN + 'ld.lld', '-m', 'elf_i386', '-T', ld, '-o', elf, obj, '-e0'],
                       capture_output=True, text=True)
    if r.returncode:
        print(r.stderr[-3000:])
        raise SystemExit('link %s failed' % section)
    d = open(elf, 'rb').read()
    shoff, = struct.unpack_from('<I', d, 0x20)
    shnum, shstrndx = struct.unpack_from('<HH', d, 0x30)
    sh = [struct.unpack_from('<IIIIIIIIII', d, shoff + 40 * i) for i in range(shnum)]
    strt = sh[shstrndx]; names = d[strt[4]:strt[4] + strt[5]]
    got = None
    for s in sh:
        nm = names[s[0]:names.index(b'\0', s[0])].decode()
        if nm == section:
            # sh_addr, sh_offset, sh_size = s[3], s[4], s[5]
            got = d[s[4]:s[4] + s[5]]
            addr = s[3]
            if addr != va:
                print('warning %s linked at %x wanted %x' % (section, addr, va))
            break
    if got is None:
        raise SystemExit('section %s missing from ELF' % section)
    if got != want:
        n = 0
        first = None
        for i, (a, b) in enumerate(zip(got, want)):
            if a != b:
                if first is None:
                    first = i
                    print('MISMATCH %s +0x%x (VA %08x) got=%02x want=%02x' % (section, i, va + i, a, b))
                n += 1
        if len(got) != len(want):
            print('length got %d want %d' % (len(got), len(want)))
        print('  %d differing bytes' % n)
        return False, got
    open(out_bin, 'wb').write(got)
    print('%s MATCH vanilla %d bytes md5 %s' % (section, len(got), hashlib.md5(got).hexdigest()))
    return True, got

def write_tsv(path, labs, va0, end):
    rows = ['#va\tlabel\ttype\tsize']
    for va in sorted(labs):
        if va0 <= va < end:
            nm, typ, sz = labs[va]
            rows.append('%08x\t%s\t%s\t%s' % (va, nm, typ, sz))
    open(path, 'w').write('\n'.join(rows) + '\n')

def emit_bss(labs, bss_va, bss_end):
    points = sorted(va for va in labs if bss_va <= va < bss_end) + [bss_end]
    lines = [
        '# GENERATED by tools/gen_data.py — BSS tail of .data (not in the file image)',
        '.code32',
        '.section .bss,"aw",@nobits',
    ]
    used = set()
    prev = bss_va
    if points[0] != bss_va:
        lines.append('.La%08x:' % bss_va)
        lines.append('  .zero %d' % (points[0] - bss_va))
        prev = points[0]
    for i, va in enumerate(points):
        if va == bss_end:
            if prev < bss_end:
                lines.append('.La%08x:' % prev)
                lines.append('  .zero %d' % (bss_end - prev))
            break
        nm, typ, sz = labs[va]
        if nm in used:
            nm = nm + ('_%08x' % va)
        used.add(nm)
        nxt = points[i + 1]
        lines.append('%s:  # %08x %s' % (nm, va, typ))
        lines.append('.La%08x:' % va)
        # size: prefer declared size if it fits, else to next label
        nbytes = nxt - va
        lines.append('  .zero %d' % nbytes)
        prev = nxt
    return '\n'.join(lines) + '\n', bss_end - bss_va

def assemble_bss(src_path, bss_va, size):
    os.makedirs(BUILD, exist_ok=True)
    obj = os.path.join(BUILD, 'bss.o')
    elf = os.path.join(BUILD, 'bss.elf')
    ld = os.path.join(BUILD, 'bss.ld')
    open(ld, 'w').write('SECTIONS {\n  .bss 0x%x : { *(.bss) }\n}\n' % bss_va)
    r = subprocess.run([BIN + 'clang', '--target=i686-linux-gnu', '-c', src_path, '-o', obj],
                       capture_output=True, text=True)
    if r.returncode:
        print(r.stderr[-3000:])
        raise SystemExit('assemble bss failed')
    r = subprocess.run([BIN + 'ld.lld', '-m', 'elf_i386', '-T', ld, '-o', elf, obj, '-e0'],
                       capture_output=True, text=True)
    if r.returncode:
        print(r.stderr[-3000:])
        raise SystemExit('link bss failed')
    d = open(elf, 'rb').read()
    shoff, = struct.unpack_from('<I', d, 0x20)
    shnum, shstrndx = struct.unpack_from('<HH', d, 0x30)
    sh = [struct.unpack_from('<IIIIIIIIII', d, shoff + 40 * i) for i in range(shnum)]
    strt = sh[shstrndx]; names = d[strt[4]:strt[4] + strt[5]]
    for s in sh:
        nm = names[s[0]:names.index(b'\0', s[0])].decode()
        if nm == '.bss':
            # sh_addr=s[3], sh_size=s[5], sh_type=s[1], sh_offset=s[4]
            typ, addr, sz = s[1], s[3], s[5]
            print('bss ELF addr %x size %d type %d (8=NOBITS) wanted size %d' % (addr, sz, typ, size))
            return addr == bss_va and sz == size
    print('bss section missing')
    return False

def main():
    os.makedirs(OUT_R, exist_ok=True)
    os.makedirs(OUT_D, exist_ok=True)
    os.makedirs(BUILD, exist_ok=True)
    pe, rdata, r_rawsize, data, d_vsize, d_rawsize = pe_sections()
    bss_va = DATA_VA + d_rawsize
    data_end = DATA_VA + d_vsize
    rdata_end = RDATA_VA + len(rdata)
    print('.rdata vsize %d rawsize %d' % (len(rdata), r_rawsize))
    print('.data  init %d bss %d vsize %d' % (len(data), d_vsize - d_rawsize, d_vsize))
    labs = load_labels(rdata_end=rdata_end, data_end=data_end)
    nr = sum(1 for v in labs if RDATA_VA <= v < rdata_end)
    nd = sum(1 for v in labs if DATA_VA <= v < bss_va)
    nb = sum(1 for v in labs if bss_va <= v < data_end)
    print('labels rdata %d init-data %d bss %d' % (nr, nd, nb))

    r_s = emit_bytes(rdata, RDATA_VA, labs, '.rdata')
    open(os.path.join(OUT_R, 'rdata.s'), 'w').write(r_s)
    write_tsv(os.path.join(OUT_R, 'rdata.tsv'), labs, RDATA_VA, rdata_end)
    ok_r, got_r = assemble('.rdata', RDATA_VA, os.path.join(OUT_R, 'rdata.s'),
                           os.path.join(OUT_R, 'rdata.bin'), rdata)
    if ok_r:
        open(os.path.join(OUT_R, 'rdata.raw'), 'wb').write(got_r.ljust(r_rawsize, b'\0'))
        pad = pe.sections[1].get_data()[len(rdata):r_rawsize]
        if pad != b'\x00' * (r_rawsize - len(rdata)):
            print('unexpected .rdata raw padding')
            ok_r = False
        elif got_r.ljust(r_rawsize, b'\0') != pe.sections[1].get_data()[:r_rawsize]:
            print('.rdata rawsize mismatch')
            ok_r = False
        else:
            print('rdata.raw MATCH vanilla rawsize %d' % r_rawsize)

    d_s = emit_bytes(data, DATA_VA, labs, '.data')
    open(os.path.join(OUT_D, 'data.s'), 'w').write(d_s)
    write_tsv(os.path.join(OUT_D, 'data.tsv'), labs, DATA_VA, bss_va)
    ok_d, got_d = assemble('.data', DATA_VA, os.path.join(OUT_D, 'data.s'),
                           os.path.join(OUT_D, 'data.bin'), data)

    bss_s, bss_sz = emit_bss(labs, bss_va, data_end)
    open(os.path.join(OUT_D, 'bss.s'), 'w').write(bss_s)
    write_tsv(os.path.join(OUT_D, 'bss.tsv'), labs, bss_va, data_end)
    # vanilla BSS is not in the file; the mapped tail must be zeros
    mapped = pe.sections[2].get_data()
    # get_data() is typically rawsize; virtual tail is implicit zeros
    print('bss size %d labels %d' % (bss_sz, nb))
    ok_b = assemble_bss(os.path.join(OUT_D, 'bss.s'), bss_va, bss_sz)
    if not ok_b:
        print('BSS ELF size/addr mismatch')

    if ok_r and ok_d and ok_b:
        print('STEP7 data source OK')
        return 0
    print('STEP7 FAIL rdata=%s data=%s bss=%s' % (ok_r, ok_d, ok_b))
    return 1

if __name__ == '__main__':
    sys.exit(main())
