#!/usr/bin/env python3
"""gen_rsrc.py: source the vanilla lomse.exe .rsrc section (VA 0x005d7000, 2432 bytes).

Extracts the five resources to src/rsrc/*.bin, writes lomse.rc + rsrc.tsv, and
rebuilds a byte-identical .rsrc image (src/rsrc/rsrc.bin) from those sources.

Layout (MSVC-style, verified against vanilla):
  * 3-level tree, types in ID order (ICON, DIALOG, ACCELERATOR, GROUP_ICON, VERSION)
  * breadth-first directories: root, then all name dirs, then all lang dirs (Lang 1033),
    then data entries, then the ACCEL_KEYS name string, then 16-byte-aligned data
  * data blob order: ICON, GROUP_ICON packed immediately after it, then DIALOG,
    VERSION, ACCELERATOR each starting 16-byte aligned (zero pad)
  * trailing file-section pad to rawsize 2560 is zeros (not part of vsize 2432)

Usage:
  python3 tools/gen_rsrc.py              # extract + rebuild + compare to vanilla
  python3 tools/gen_rsrc.py --rebuild    # rebuild from existing bins/tsv only
"""
import os, sys, struct, hashlib
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lomdb
R = lomdb.ROOT
SRC = os.path.join(R, 'src', 'rsrc')
ORIG = '/workspace/lom_project/game/LoM/English/lomse.exe'
RSRC_VA = 0x005d7000
RSRC_RVA = 0x001d7000
VSIZE = 2432
RAWSIZE = 2560
LANG = 1033  # 0x0409

# type_id, name (int or str), bin filename, rc kind
RESOURCES = [
    (3,  1,            'icon_1.bin',           'ICON'),
    (5,  102,          'dialog_102.bin',       'DIALOG'),
    (9,  'ACCEL_KEYS', 'accel_ACCEL_KEYS.bin', 'ACCELERATOR'),
    (14, 101,          'group_icon_101.bin',   'GROUP_ICON'),
    (16, 1,            'version_1.bin',        'VERSION'),
]
# Data payload order in the section (not type-ID order).
DATA_ORDER = [3, 14, 5, 16, 9]  # ICON, GROUP_ICON, DIALOG, VERSION, ACCELERATOR
PACK_AFTER = {14: 3}  # GROUP_ICON packed immediately after ICON; others 16-aligned

def vanilla_rsrc():
    import pefile
    pe = pefile.PE(ORIG)
    rs = [s for s in pe.sections if s.Name.startswith(b'.rsrc')][0]
    assert 0x400000 + rs.VirtualAddress == RSRC_VA
    assert rs.Misc_VirtualSize == VSIZE
    assert rs.SizeOfRawData == RAWSIZE
    data = rs.get_data()[:RAWSIZE]
    return pe, data

def extract():
    os.makedirs(SRC, exist_ok=True)
    pe, raw = vanilla_rsrc()
    v = raw[:VSIZE]
    rows = []
    def ident(e):
        return e.name.string if e.name else e.id
    # walk pefile
    found = {}
    for typ in pe.DIRECTORY_ENTRY_RESOURCE.entries:
        tid = typ.id
        for nam in typ.directory.entries:
            n = nam.name.string if nam.name else nam.id
            for lang in nam.directory.entries:
                d = lang.data
                blob = pe.get_data(d.struct.OffsetToData, d.struct.Size)
                found[(tid, n if not isinstance(n, bytes) else n.decode())] = (
                    lang.id, d.struct.OffsetToData, blob)
    tsv = ['#type_id\tname\tlang\trva\tsize\tfile']
    for tid, name, fn, kind in RESOURCES:
        key = (tid, name)
        if key not in found:
            raise SystemExit('missing resource %s' % (key,))
        lang, rva, blob = found[key]
        open(os.path.join(SRC, fn), 'wb').write(blob)
        tsv.append('%d\t%s\t%d\t%08x\t%d\t%s' % (tid, name, lang, rva, len(blob), fn))
        print('extracted', kind, name, 'rva', hex(rva), 'size', len(blob), 'md5', hashlib.md5(blob).hexdigest())
    open(os.path.join(SRC, 'rsrc.tsv'), 'w').write('\n'.join(tsv) + '\n')
    write_rc()
    write_ico(os.path.join(SRC, 'icon_1.bin'), os.path.join(SRC, 'group_icon_101.bin'),
              os.path.join(SRC, 'icon_1.ico'))
    return v, raw

def write_ico(icon_bin, group_bin, ico_path):
    icon = open(icon_bin, 'rb').read()
    grp = open(group_bin, 'rb').read()
    # ICO: ICONDIR + ICONDIRENTRY (offset instead of nID) + image
    # GRP: reserved,type,count + (w,h,colors,res,planes,bitcount,bytes,id)
    reserved, typ, count = struct.unpack_from('<HHH', grp)
    w, h, colors, res, planes, bitcount, nbytes, nid = struct.unpack_from('<BBBBHHIH', grp, 6)
    hdr = struct.pack('<HHH', reserved, typ, count)
    # dwImageOffset = 6 + 16
    entry = struct.pack('<BBBBHHII', w, h, colors, res, planes, bitcount, nbytes, 6 + 16)
    open(ico_path, 'wb').write(hdr + entry + icon)

def write_rc():
    # Readable source describing the five resources. Payloads that must be
    # byte-exact (dialog template, version info, accel table, icon image) stay
    # in the companion .bin files; this .rc is the inventory + reconstructed
    # script for DIALOG / ACCELERATORS / VERSION / ICON.
    acc = open(os.path.join(SRC, 'accel_ACCEL_KEYS.bin'), 'rb').read()
    lines = [
        '/* lomse.exe .rsrc — generated by tools/gen_rsrc.py from vanilla SE 3.01.',
        '   Official section image is built by gen_rsrc.py from rsrc.tsv + *.bin',
        '   (byte-identical to VA 0x005d7000, 2432 bytes). This .rc documents the',
        '   five resources and can be fed to llvm-windres for a non-identity check. */',
        '#include <windows.h>',
        '',
        '1 ICON "icon_1.ico"',
        '',
        '101 GROUPICON "icon_1.ico"  /* vanilla is a separate RT_GROUP_ICON 101 -> icon 1 */',
        '',
        '102 DIALOG 0, 0, 269, 122',
        'STYLE WS_CAPTION | WS_SYSMENU | DS_MODALFRAME | DS_SETFONT',
        'CAPTION "Script Window"',
        'FONT 8, "MS Sans Serif"',
        'BEGIN',
        '    LISTBOX         1002, 7, 7, 202, 78, 0x50b10501',
        '    PUSHBUTTON      "Clear", 1004, 215, 20, 50, 14, 0x50010000',
        '    EDITTEXT        1006, 217, 69, 40, 14, 0x50812801',
        '    LTEXT           "Stack Entries", -1, 215, 57, 43, 8, 0x50020001',
        '    EDITTEXT        1000, 7, 86, 202, 29, 0x50811084',
        'END',
        '',
        'ACCEL_KEYS ACCELERATORS',
        'BEGIN',
    ]
    for i in range(len(acc)//8):
        fVirt, key, cmd, pad = struct.unpack_from('<HHHH', acc, i*8)
        flags = []
        if fVirt & 0x01: flags.append('VIRTKEY')
        if fVirt & 0x02: flags.append('NOINVERT')
        if fVirt & 0x04: flags.append('SHIFT')
        if fVirt & 0x08: flags.append('CONTROL')
        if fVirt & 0x10: flags.append('ALT')
        # 0x80 on the last vanilla entry is preserved only in the .bin
        if 32 <= key < 127 and chr(key).isalnum():
            krepr = '"%s"' % chr(key) if not chr(key).isdigit() else '"%s"' % chr(key)
            # digits and letters: use VK or quoted char
            krepr = '"%s"' % chr(key)
        elif key == 0x60:
            krepr = 'VK_OEM_3'  # '`' — keep raw too
            krepr = '0x%02x' % key
        else:
            krepr = '0x%02x' % key
        fl = ', '.join(flags) if flags else '0'
        lines.append('    %s, %d, %s  /* fVirt=0x%04x pad=%d */' % (krepr, cmd, fl, fVirt, pad))
    lines += [
        'END',
        '',
        '1 VERSIONINFO',
        'FILEVERSION 3,0,1,1',
        'PRODUCTVERSION 3,0,1,1',
        'FILEFLAGSMASK 0x3F',
        'FILEFLAGS 0x0',
        'FILEOS 0x40004',
        'FILETYPE 0x1',
        'FILESUBTYPE 0x0',
        'BEGIN',
        '    BLOCK "StringFileInfo"',
        '    BEGIN',
        '        BLOCK "040904b0"',
        '        BEGIN',
        '            VALUE "CompanyName", "Impressions"',
        '            VALUE "FileDescription", "lomse"',
        '            VALUE "FileVersion", "3.01"',
        '            VALUE "InternalName", "lomse"',
        '            VALUE "LegalCopyright", "Copyright © 1998"',
        '            VALUE "LegalTrademarks", " Sierra Online"',
        '            VALUE "OriginalFilename", "lomse.exe"',
        '            VALUE "ProductName", "Lords of Magic Special Edition"',
        '            VALUE "ProductVersion", "3.01"',
        '        END',
        '    END',
        '    BLOCK "VarFileInfo"',
        '    BEGIN',
        '        VALUE "Translation", 0x0409, 0x04b0',
        '    END',
        'END',
        '',
    ]
    open(os.path.join(SRC, 'lomse.rc'), 'w').write('\n'.join(lines) + '\n')

def load_inventory():
    items = []
    for tid, name, fn, kind in RESOURCES:
        blob = open(os.path.join(SRC, fn), 'rb').read()
        items.append(dict(tid=tid, name=name, fn=fn, kind=kind, blob=blob))
    return items

def align(n, a):
    return (n + a - 1) // a * a

def build(items=None):
    """Rebuild the 2432-byte .rsrc image from src/rsrc bins."""
    if items is None:
        items = load_inventory()
    by_tid = {it['tid']: it for it in items}
    # --- directories, breadth-first ---
    # root at 0, 0 named + 5 id
    types = sorted((it['tid'], it) for it in items)
    # sizes
    def dir_size(nents):
        return 16 + 8 * nents
    root_off = 0
    off = dir_size(len(types))  # 0x38
    name_off = {}
    for tid, it in types:
        name_off[tid] = off
        off += dir_size(1)
    lang_off = {}
    for tid, it in types:
        lang_off[tid] = off
        off += dir_size(1)
    dataent_off = {}
    for tid, it in types:
        dataent_off[tid] = off
        off += 16
    # name string for ACCEL_KEYS
    string_off = {}
    for tid, it in types:
        if isinstance(it['name'], str):
            string_off[tid] = off
            # WORD length + WCHAR[] , no extra NUL in the counted string
            off += 2 + 2 * len(it['name'])
    # pad to 16 before first data
    off = align(off, 16)
    # data blobs
    data_off = {}
    prev_tid = None
    prev_end = off
    for tid in DATA_ORDER:
        it = by_tid[tid]
        if tid in PACK_AFTER:
            # pack immediately after the referenced type
            src = PACK_AFTER[tid]
            pos = data_off[src] + len(by_tid[src]['blob'])
        else:
            pos = align(prev_end if prev_tid is not None else off, 16)
            if prev_tid is None:
                pos = off
        data_off[tid] = pos
        prev_end = pos + len(it['blob'])
        prev_tid = tid
    end = prev_end
    if end != VSIZE:
        # allow explicit pad to VSIZE
        if end > VSIZE:
            raise SystemExit('rsrc overflow %d > %d' % (end, VSIZE))
    img = bytearray(VSIZE)

    def put_dir(doff, named, ids):
        # named/ids: list of (name_or_id, is_name, child_off, is_dir)
        struct.pack_into('<IIHHHH', img, doff, 0, 0, 0, 0, len(named), len(ids))
        p = doff + 16
        for name, is_name, child, is_dir in named + ids:
            nm = (name | 0x80000000) if is_name else name
            ch = (child | 0x80000000) if is_dir else child
            struct.pack_into('<II', img, p, nm, ch)
            p += 8

    put_dir(root_off, [], [
        (tid, False, name_off[tid], True) for tid, it in types
    ])
    for tid, it in types:
        if isinstance(it['name'], str):
            put_dir(name_off[tid], [
                (string_off[tid], True, lang_off[tid], True)
            ], [])
        else:
            put_dir(name_off[tid], [], [
                (it['name'], False, lang_off[tid], True)
            ])
        put_dir(lang_off[tid], [], [
            (LANG, False, dataent_off[tid], False)
        ])
        # data entry: RVA, size, codepage 0, reserved 0
        rva = RSRC_RVA + data_off[tid]
        struct.pack_into('<IIII', img, dataent_off[tid], rva, len(it['blob']), 0, 0)
        img[data_off[tid]:data_off[tid] + len(it['blob'])] = it['blob']
    for tid, it in types:
        if isinstance(it['name'], str):
            s = it['name']
            o = string_off[tid]
            struct.pack_into('<H', img, o, len(s))
            img[o+2:o+2+2*len(s)] = s.encode('utf-16le')
    return bytes(img)

def compare(built, vanilla_vsize):
    if built == vanilla_vsize:
        print('rsrc.bin MATCH vanilla .rsrc vsize (%d bytes, md5 %s)' % (
            len(built), hashlib.md5(built).hexdigest()))
        return True
    print('rsrc.bin MISMATCH vanilla .rsrc')
    n = 0
    for i, (a, b) in enumerate(zip(built, vanilla_vsize)):
        if a != b:
            if n < 16:
                print('  first differ +0x%x built=%02x vanilla=%02x' % (i, a, b))
            n += 1
    if len(built) != len(vanilla_vsize):
        print('  length built %d vanilla %d' % (len(built), len(vanilla_vsize)))
    print('  %d differing bytes' % n)
    return False

def main():
    os.makedirs(SRC, exist_ok=True)
    rebuild_only = '--rebuild' in sys.argv
    pe, raw = vanilla_rsrc()
    vanilla_v = raw[:VSIZE]
    if not rebuild_only or not os.path.exists(os.path.join(SRC, 'rsrc.tsv')):
        extract()
    built = build()
    open(os.path.join(SRC, 'rsrc.bin'), 'wb').write(built)
    open(os.path.join(SRC, 'rsrc.raw'), 'wb').write(built.ljust(RAWSIZE, b'\0'))
    ok = compare(built, vanilla_v)
    pad = raw[VSIZE:RAWSIZE]
    if pad != b'\x00' * (RAWSIZE - VSIZE):
        print('unexpected vanilla raw padding')
        ok = False
    else:
        print('vanilla rawsize pad %d zeros OK' % (RAWSIZE - VSIZE))
    if built.ljust(RAWSIZE, b'\0') != raw:
        print('rawsize (2560) image mismatch after zero pad')
        ok = False
    else:
        print('rsrc.raw MATCH vanilla .rsrc rawsize (%d bytes)' % RAWSIZE)
    if not ok:
        sys.exit(1)
    print('STEP6 rsrc source OK')

if __name__ == '__main__':
    main()
