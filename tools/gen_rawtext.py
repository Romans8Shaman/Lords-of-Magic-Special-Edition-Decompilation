#!/usr/bin/env python3
"""gen_rawtext.py RAW_RANGES.tsv OUTBINDIR : the .text byte ranges a standalone build still needs from the original
(uncovered fns, bodyref fns, gaps: padding / jump tables / noncontiguous chunks) as ASSEMBLY SOURCE
src/rawtext/rawtext.s (one section per range at its fixed address, AT&T via capstone, branch targets as labels or
absolute addresses), assembled (clang i686 ELF) + linked (ld.lld, linker script with fixed addresses) and checked
byte-for-byte against lomse.exe. Instructions whose re-encoding differs (or undecodable data) are emitted as
.byte with the disassembly as a comment; padding runs as .fill. Writes OUTBINDIR/<lo>.bin per range + stats."""
import sys, os, re, subprocess, struct
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lomdb
from capstone import Cs, CS_ARCH_X86, CS_MODE_32, CS_OPT_SYNTAX_ATT
R = lomdb.ROOT
BIN = '/opt/llvm-mingw/bin/'
mi = Cs(CS_ARCH_X86, CS_MODE_32)
ma = Cs(CS_ARCH_X86, CS_MODE_32); ma.syntax = CS_OPT_SYNTAX_ATT
BR = re.compile(r'^(j\w+|call|loop\w*|jecxz|jcxz)$')
def emit(lo, hi, forced):
    code = lomdb.read_va(lo, hi - lo)
    out = ['.section .r%08x,"ax",@progbits' % lo, '.Lr%08x:' % lo]
    k = 0; ins = {}
    # pass 1: instruction boundaries (linear sweep; undecodable byte -> data)
    seq = []
    while k < len(code):
        a = lo + k
        if code[k] in (0xcc, 0x90) and a not in forced:
            j = k
            while j < len(code) and code[j] == code[k]: j += 1
            if j - k >= 2 or code[k] == 0xcc:
                seq.append(('fill', a, j - k, code[k])); k = j; continue
        it = list(ma.disasm(code[k:k + 16], a, 1))
        if not it or a in forced:
            n = it[0].size if it else 1
            seq.append(('byte', a, code[k:k + n], (it[0].mnemonic + ' ' + it[0].op_str) if it else '?')); k += n; continue
        i = it[0]; seq.append(('ins', a, i)); k += i.size
    starts = {s[1] for s in seq}
    for s in seq:
        if s[0] == 'fill':
            out.append('.La%08x: .fill %d,1,0x%02x' % (s[1], s[2], s[3]))
        elif s[0] == 'byte':
            out.append('.La%08x: .byte %s  # %s' % (s[1], ','.join('0x%02x' % b for b in s[2]), s[3]))
        else:
            i = s[2]; m, op = i.mnemonic, i.op_str
            if BR.match(m) and re.fullmatch(r'0x[0-9a-f]+', op):
                t = int(op, 16)
                tgt = ('.La%08x' % t) if (lo <= t < hi and t in starts) else ('0x%x' % t)
                pre = '{disp32} ' if (i.size >= 5 and m != 'call') or (m.startswith('j') and m != 'jmp' and i.size == 6) else ''
                if m == 'call': pre = ''
                out.append('.La%08x: %s%s %s' % (i.address, pre, m, tgt))
            else:
                out.append('.La%08x: %s %s' % (i.address, m, op))
    return out
def main():
    rr = [tuple(int(x, 16) for x in l.split()) for l in open(sys.argv[1]) if l.strip()]
    outd = sys.argv[2]; os.makedirs(outd, exist_ok=True)
    forced = set()
    if os.path.exists(os.path.join(R, 'src', 'rawtext', 'forced.txt')):
        forced = {int(x, 16) for x in open(os.path.join(R, 'src', 'rawtext', 'forced.txt')).read().split()}
    for rnd in range(400):
        S = ['# GENERATED by tools/gen_rawtext.py: original-layout .text pieces not (yet) rebuilt as functions', '.code32']
        for lo, hi in rr: S += emit(lo, hi, forced)
        sp = os.path.join(R, 'src', 'rawtext', 'rawtext.s'); open(sp, 'w').write('\n'.join(S) + '\n')
        ld = os.path.join(R, 'src', 'rawtext', 'rawtext.ld')
        open(ld, 'w').write('SECTIONS {\n' + ''.join('  .r%08x 0x%x : { *(.r%08x) }\n' % (lo, lo, lo) for lo, hi in rr) + '}\n')
        o = os.path.join(outd, 'rawtext.o'); e = os.path.join(outd, 'rawtext.elf')
        r = subprocess.run([BIN + 'clang', '--target=i686-linux-gnu', '-c', sp, '-o', o], capture_output=True, text=True)
        if r.returncode:
            # assembler rejects some capstone spellings -> force those instructions to .byte and retry
            L = S
            bad = set()
            for m in re.finditer(r'rawtext\.s:(\d+):\d+: error', r.stderr):
                ln = L[int(m.group(1)) - 1]; mm = re.match(r'\.La([0-9a-f]{8}):', ln)
                if mm: bad.add(int(mm.group(1), 16))
            if not bad or bad <= forced: print(r.stderr[-3000:]); sys.exit(1)
            forced |= bad; print('round', rnd, 'asm errors forced', len(bad)); continue
        # pre-link check on the object: section sizes + bytes outside relocated fields
        d = open(o, 'rb').read()
        shoff, = struct.unpack_from('<I', d, 0x20); shnum, shstrndx = struct.unpack_from('<HH', d, 0x30)
        sh = [struct.unpack_from('<IIIIIIIIII', d, shoff + 40 * i) for i in range(shnum)]
        strt = sh[shstrndx]; names = d[strt[4]:strt[4] + strt[5]]
        nmof = lambda s: names[s[0]:names.index(b'\0', s[0])].decode()
        relmask = {}
        for s_ in sh:
            if s_[1] == 9:
                tgt = sh[s_[7]]; m = relmask.setdefault(nmof(tgt), set())
                for q in range(s_[4], s_[4] + s_[5], 8):
                    off, = struct.unpack_from('<I', d, q); m.update(range(off, off + 4))
        objsec = {int(nmof(s_)[2:], 16): d[s_[4]:s_[4] + s_[5]] for s_ in sh if nmof(s_).startswith('.r') and s_[1] == 1}
        newf = set()
        for lo, hi in rr:
            b = objsec[lo]; want = lomdb.read_va(lo, hi - lo); m = relmask.get('.r%08x' % lo, set())
            if len(b) == len(want) and all(b[x] == want[x] or x in m for x in range(len(b))): continue
            n = min(len(b), len(want))
            j = next((x for x in range(n) if b[x] != want[x] and x not in m), n)
            st = [int(q, 16) for q in re.findall(r'^\.La([0-9a-f]{8}):', '\n'.join(emit(lo, hi, forced)), re.M)]
            cand = max(x for x in st if x <= lo + j)
            if cand in forced: print('stuck(obj)', hex(lo), hex(cand), j, len(b), len(want)); sys.exit(1)
            newf.add(cand)
        if newf:
            forced |= newf; print('round', rnd, 'object mismatches forced', len(newf)); continue
        r = subprocess.run([BIN + 'ld.lld', '-m', 'elf_i386', '-T', ld, '-o', e, o, '--no-check-sections' if False else '-e0'], capture_output=True, text=True)
        if r.returncode: print(r.stderr[-3000:]); sys.exit(1)
        # read section bytes from the ELF
        d = open(e, 'rb').read()
        shoff, = struct.unpack_from('<I', d, 0x20); shnum, shstrndx = struct.unpack_from('<HH', d, 0x30)
        sh = [struct.unpack_from('<IIIIIIIIII', d, shoff + 40 * i) for i in range(shnum)]
        strt = sh[shstrndx]; names = d[strt[4]:strt[4] + strt[5]]
        secs = {}
        for s in sh:
            nm = names[s[0]:names.index(b'\0', s[0])].decode()
            if nm.startswith('.r'): secs[int(nm[2:], 16)] = (s[3], d[s[4]:s[4] + s[5]])
        newf = set(); bad = 0
        for lo, hi in rr:
            addr, b = secs[lo]; want = lomdb.read_va(lo, hi - lo)
            if b == want: continue
            bad += 1
            # first differing byte -> force the instruction containing it to .byte
            j = next((x for x in range(min(len(b), len(want))) if b[x] != want[x]), min(len(b), len(want)))
            # instruction start at/before lo+j from the emitted sequence
            st = [int(m, 16) for m in re.findall(r'^\.La([0-9a-f]{8}):', '\n'.join(emit(lo, hi, forced)), re.M)]
            cand = max(x for x in st if x <= lo + j)
            if cand in forced: print('stuck', hex(lo), hex(cand)); sys.exit(1)
            newf.add(cand)
        print('round', rnd, 'ranges', len(rr), 'mismatch', bad, 'newly forced', len(newf))
        if not newf: break
        forced |= newf
        open(os.path.join(R, 'src', 'rawtext', 'forced.txt'), 'w').write('\n'.join('%08x' % x for x in sorted(forced)) + '\n')
    for lo, hi in rr: open(os.path.join(outd, '%08x.bin' % lo), 'wb').write(secs[lo][1])
    txt = open(sp).read()
    nfill = sum(int(m) for m in re.findall(r'\.fill (\d+),', txt)); nbyte = sum(len(m.split(',')) for m in re.findall(r': \.byte ([^#\n]+)', txt))
    nins = len(re.findall(r'^\.La[0-9a-f]{8}: (?!\.fill|\.byte)', txt, re.M))
    print('ranges', len(rr), 'bytes', sum(h - l for l, h in rr), 'instructions', nins, 'fill bytes', nfill, '.byte bytes', nbyte)
main()
